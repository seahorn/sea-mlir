# gen-dialect-doc: generate the reference of the sea dialect (ops, types,
# enums) from its ODS with mlir-tblgen -gen-dialect-doc, as MLIR projects
# do, into docs/reference/dialect.md (committed; `just docs-dialect` runs it).
#
#   utils/gen-dialect-doc.sh [<mlir-tblgen>]
#
# mlir-tblgen: the argument, else $MLIR_TBLGEN, else the one of the LLVM
# install named by build-release/CMakeCache.txt (MLIR_DIR; in a linked
# worktree also the main checkout's), else PATH.
# The build also generates the op part alone: `ninja -C <build> mlir-doc`
# (add_mlir_doc, <build>/docs/Sea/SeaOps.md).
set -euo pipefail
SRC="$(cd "$(dirname "$0")/.." && pwd)"
TBLGEN="${1:-${MLIR_TBLGEN:-}}"
if [[ -z "$TBLGEN" ]]; then
  # a linked worktree has no build: also try the main checkout's
  MAIN="$(git -C "$SRC" rev-parse --path-format=absolute --git-common-dir 2>/dev/null || true)"
  MAIN="${MAIN%/.git}"
  for cache in "$SRC/build-release/CMakeCache.txt" "$SRC/build/CMakeCache.txt" \
               "$MAIN/build-release/CMakeCache.txt" "$MAIN/build/CMakeCache.txt"; do
    [[ -f "$cache" ]] || continue
    dir="$(sed -n 's/^MLIR_DIR:[A-Z]*=//p' "$cache")"
    if [[ -n "$dir" && -x "$dir/../../../bin/mlir-tblgen" ]]; then
      TBLGEN="$dir/../../../bin/mlir-tblgen"; break
    fi
  done
fi
TBLGEN="${TBLGEN:-$(command -v mlir-tblgen || true)}"
[[ -n "$TBLGEN" && -x "$TBLGEN" ]] || {
  echo "gen-dialect-doc: no mlir-tblgen (pass it, or set MLIR_TBLGEN)" >&2; exit 1; }
INC="$("$TBLGEN" --version >/dev/null 2>&1; cd "$(dirname "$TBLGEN")/../include" && pwd)"
OUT="$SRC/docs/reference/dialect.md"
TMP="$(mktemp)"
"$TBLGEN" -gen-dialect-doc -dialect=sea -I "$SRC/include" -I "$INC" \
  "$SRC/include/sea/Dialect/Sea/SeaOps.td" -o "$TMP"
# MkDocs renders [TOC] with the toc extension; the page title stays the
# generated one. The ODS descriptions are the source: edit the .td files.
{ echo '<!-- Generated by utils/gen-dialect-doc.sh from include/sea/Dialect/Sea/*.td; do not edit. -->'
  cat "$TMP"; } > "$OUT"
rm -f "$TMP"
echo "gen-dialect-doc: $OUT ($(grep -c '^### ' "$OUT") ops/types/enums)"
