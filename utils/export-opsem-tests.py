"""Regenerates test/SeaHorn/opsem/*.mlir from SeaHorn's opsem tests.

For each SeaHorn test with a `%seabmc` RUN line, takes its FIRST
configuration (the line's extra flags, as utils/run-seahorn-tests.py reads
them), and:

  1. exports the program with SeaHorn's sea-mlir engine
     (--horn-bmc-engine=sea-mlir --horn-sea-mlir-out=...),
  2. gets the reference verdict from SeaHorn's mono engine (not from the
     test's CHECK: they differ only on XFAIL tests),
  3. runs `sea-vc --lower` on the export (what SeaHorn's
     sea-mlir engine runs) and keeps the test only if sea-vc succeeds with the reference
     verdict.

Each kept test is a lit test: a header naming its source, the SeaHorn
commit and the flags, a RUN line through sea-vc that checks the verdict,
and the exported program. These are parity regression tests, not oracles:
they record that sea-mlir agreed with SeaHorn when they were generated.
They are disposable; regenerate them with this script.

Tests not kept are listed with the reason (unsupported by sea-mlir, sea-vc
disagrees, no reference verdict). Exit status 1 when sea-vc gives a verdict
different from mono (WRONG).

  utils/export-opsem-tests.py --seahorn <seahorn>/build/bin/seahorn \\
      --tests <seahorn>/test/opsem --sea-vc build/bin/sea-vc
"""

import argparse
import concurrent.futures
import os
import re
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
# The RUN-line parser and SeaHorn's base BMC flags, shared with the parity
# driver so both read the same configurations.
_rst = __import__("run-seahorn-tests")
SEABMC = _rst.SEABMC
configurations = _rst.configurations
expected = _rst.expected

DEFAULT_OUT = os.path.join(os.path.dirname(HERE), "test", "SeaHorn", "opsem")


def run(cmd, timeout):
    """(returncode or None on timeout, stdout, stderr, seconds)."""
    t = time.monotonic()
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return None, "", "", time.monotonic() - t
    return r.returncode, r.stdout, r.stderr, time.monotonic() - t


def verdict(stdout, prefix=""):
    m = re.search(r"^" + prefix + r"(sat|unsat)$", stdout, re.M)
    return m.group(1) if m else None


def first_error(text):
    for line in text.splitlines():
        if "Error" in line or "error:" in line:
            line = re.sub(r'loc\("/[^"]*"(:\d+:\d+)?\): ', "", line)
            return line.strip()[:160]
    return None


def deterministic(program, test):
    """The exported program without run-dependent text: SeaHorn's own
    header line (it names the absolute input path) and absolute temporary
    paths in locations."""
    lines = program.splitlines()
    if lines and lines[0].startswith("// Exported from SeaHorn"):
        lines = lines[1:]
    text = "\n".join(lines) + "\n"
    text = re.sub(r'loc\("/[^"]*"(:\d+:\d+)?\)', "loc(unknown)", text)
    text = text.replace(os.path.abspath(test), os.path.basename(test))
    if re.search(r'loc\("/[^\"]*"', text):
        raise RuntimeError("absolute source path left in the export")
    return text


def process(args, test, flags, commit, workdir):
    """(name, status, detail, generated text or None, sea-vc seconds)."""
    name = os.path.splitext(os.path.basename(test))[0]
    out = os.path.join(workdir, name + ".mlir")
    rc, so, se, _ = run(
        [args.seahorn]
        + SEABMC
        + flags
        + [
            "--horn-bmc-engine=sea-mlir",
            "--horn-sea-vc=/bin/true",
            f"--horn-sea-mlir-out={out}",
            test,
        ],
        args.timeout,
    )
    if rc is None or not os.path.exists(out) or "export failed" in so + se:
        return name, "export-failed", first_error(so + se) or "no output", None, 0
    rc, so, se, _ = run(
        [args.seahorn] + SEABMC + flags + ["--horn-bmc-engine=mono", test], args.timeout
    )
    ref = verdict(so)
    if ref is None:
        return (
            name,
            "no-reference",
            "timeout" if rc is None else (first_error(se) or "no verdict"),
            None,
            0,
        )
    rc, so, se, secs = run([args.sea_vc, out, "--lower"], args.timeout)
    got = verdict(so, "result: ")
    if rc is None:
        return name, "timeout", None, None, secs
    if rc != 0 or got is None:
        return name, "unsupported", first_error(se) or f"sea-vc exit {rc}", None, secs
    if got != ref:
        return name, "WRONG", f"SeaHorn {ref}, sea-vc {got}", None, secs
    src = open(test, errors="replace").read()
    rel = os.path.relpath(test, args.checkout)
    header = [
        "// Generated by utils/export-opsem-tests.py; do not edit by hand.",
        "// Parity regression test (not an oracle; disposable: regenerate).",
        f"// Source: SeaHorn {rel} (commit {commit}), first %seabmc configuration.",
        f"// SeaHorn flags: {' '.join(SEABMC + flags)}",
        f"// Reference verdict: SeaHorn --horn-bmc-engine=mono says {ref}.",
    ]
    exp = expected(src)
    if exp and exp != ref:
        xfail = " (XFAIL there)" if "XFAIL:" in src else ""
        header.append(
            f"// Note: the SeaHorn test's CHECK says {exp}{xfail}; "
            f"mono is the reference here."
        )
    if any(fl.startswith(_rst.NOT_MODELED) for fl in flags):
        header.append(
            "// Note: flags of SeaHorn's memory model are not "
            "modeled by sea-vc (see run-seahorn-tests.py "
            "NOT_MODELED)."
        )
    header += [
        "// RUN: sea-vc %s --lower | FileCheck %s",
        f"// CHECK: {{{{^}}}}result: {ref}{{{{$}}}}",
        "",
    ]
    text = "\n".join(header) + deterministic(open(out).read(), test)
    return name, "ok", ref, text, secs


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--seahorn", required=True, help="the seahorn binary")
    ap.add_argument("--tests", required=True, help="SeaHorn's test/opsem directory")
    ap.add_argument("--sea-vc", required=True)
    ap.add_argument(
        "--out",
        default=DEFAULT_OUT,
        help="output directory (default: test/SeaHorn/opsem)",
    )
    ap.add_argument(
        "--timeout",
        type=int,
        default=180,
        help="seconds per run (mono needs ~60 s on memset.symbolic.unaligned.unsat)",
    )
    ap.add_argument("-j", type=int, default=os.cpu_count() or 4)
    args = ap.parse_args()
    args.tests = os.path.abspath(args.tests)
    args.sea_vc = os.path.abspath(args.sea_vc)

    # The SeaHorn checkout holding the tests, and its commit.
    args.checkout = subprocess.run(
        ["git", "-C", args.tests, "rev-parse", "--show-toplevel"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    commit = subprocess.run(
        ["git", "-C", args.tests, "rev-parse", "--short", "HEAD"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()

    jobs = []
    for f in sorted(os.listdir(args.tests)):
        if not f.endswith(".ll"):
            continue
        path = os.path.join(args.tests, f)
        configs = [
            flags
            for mode, flags in configurations(open(path, errors="replace").read())
            if mode == "seabmc"
        ]
        if configs:
            jobs.append((path, configs[0]))

    os.makedirs(args.out, exist_ok=True)
    with (
        tempfile.TemporaryDirectory() as work,
        concurrent.futures.ThreadPoolExecutor(args.j) as pool,
    ):
        results = list(
            pool.map(lambda j: process(args, j[0], j[1], commit, work), jobs)
        )

    kept = set()
    skipped = []
    total_secs = 0.0
    for name, status, detail, text, secs in results:
        if status == "ok":
            with open(os.path.join(args.out, name + ".mlir"), "w") as fh:
                fh.write(text)
            kept.add(name + ".mlir")
            total_secs += secs
        else:
            skipped.append((name, status, detail))
    stale = [f for f in os.listdir(args.out) if f.endswith(".mlir") and f not in kept]
    for f in stale:
        os.remove(os.path.join(args.out, f))

    print(f"seahorn-commit: {commit}")
    print(f"tests: {len(jobs)}")
    print(f"generated: {len(kept)}")
    print(f"skipped: {len(skipped)}")
    print(f"removed-stale: {len(stale)}")
    print(f"sea-vc-seconds: {total_secs:.1f}")
    for name, status, detail in sorted(skipped):
        print(f"skip: {name} {status}: {detail}")
    slow = sorted(((s, n) for n, st, _, _, s in results if st == "ok"), reverse=True)[
        :5
    ]
    for s, n in slow:
        print(f"slowest: {n} {s:.2f}s")
    sys.exit(1 if any(st == "WRONG" for _, st, _ in skipped) else 0)


if __name__ == "__main__":
    main()
